// 정규식은 긴 용어부터 매치되도록 길이 내림차순으로 정렬해 만든다
// (예: '가상자산이용자보호법'이 '가상자산'보다 먼저 잡히도록).
function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

let _re = null;
function termRegex() {
  if (_re) return _re;
  const keys = Object.keys(NEWS_GLOSSARY).map(escapeRe).sort((a, b) => b.length - a.length);
  _re = new RegExp("(" + keys.join("|") + ")", "g");
  return _re;
}

export function newsTermRegex() {
  // 매 호출 새 lastIndex를 갖도록 복제해 반환(전역 상태 오염 방지).
  const base = termRegex();
  return new RegExp(base.source, "g");
}

// 텍스트에 등장하는 용어 키를 등장 순서대로, 중복 없이 반환.
// 같은 설명을 가진 변형(김프/김치프리미엄)은 하나로 접는다.
export function findNewsTerms(text) {
  if (!text) return [];
  const re = newsTermRegex();
  const seenText = new Set();
  const out = [];
  let m;
  while ((m = re.exec(text)) !== null) {
    const key = m[0];
    const desc = NEWS_GLOSSARY[key];
    if (seenText.has(desc)) continue;
    seenText.add(desc);
    out.push(key);
  }
  return out;
}
